from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True, slots=True)
class ImageAttachment:
    """One image attached to a message, as a base64 data URL.

    ``data_url`` is the OpenAI-compatible ``data:image/jpeg;base64,...`` payload
    passed directly to vision models. ``telegram_file_id`` is kept for
    diagnostics / re-sending the photo later and is never sent to the model.
    ``description`` is an optional short text label (generated by the photo
    captioner) that makes a bare photo findable "by meaning" in RAG.
    """

    data_url: str
    mime_type: str = "image/jpeg"
    telegram_file_id: str | None = None
    description: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return image_attachment_to_dict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ImageAttachment:
        del cls
        return image_attachment_from_dict(data)


def image_attachment_to_dict(attachment: ImageAttachment) -> dict[str, Any]:
    return {
        "data_url": attachment.data_url,
        "mime_type": attachment.mime_type,
        "telegram_file_id": attachment.telegram_file_id,
        "description": attachment.description,
    }


def image_attachment_from_dict(data: dict[str, Any]) -> ImageAttachment:
    return ImageAttachment(
        data_url=str(data.get("data_url", "")),
        mime_type=str(data.get("mime_type") or "image/jpeg"),
        telegram_file_id=data.get("telegram_file_id"),
        description=data.get("description"),
    )


def attachments_to_dicts(attachments: tuple[ImageAttachment, ...]) -> list[dict[str, Any]]:
    return [image_attachment_to_dict(attachment) for attachment in attachments]


def attachments_from_dicts(data: list[dict[str, Any]] | None) -> tuple[ImageAttachment, ...]:
    if not data:
        return ()
    return tuple(
        image_attachment_from_dict(item) for item in data if isinstance(item, dict)
    )
